package controllers

import (
	"fmt"
	"reflect"
	"runtime"
	"slices"

	. "github.com/BeamFoundry/rays/pkg/core"
	. "github.com/BeamFoundry/rays/pkg/lang"
	. "github.com/BeamFoundry/rays/pkg/web"

	. "github.com/BeamFoundry/rays-fiber/pkg/core"

	"github.com/gofiber/fiber/v3"
)

type RequestMappingMethods struct {
	GET,
	HEAD,
	POST,
	PUT,
	PATCH,
	DELETE,
	CONNECT,
	OPTIONS,
	TRACE,
	USE,
	ALL Enum[RequestMappingMethods]
}

type RequestMappingMethod = Enum[RequestMappingMethods]

type FiberControllerConfig struct {
	provider  *DefaultAppProvider `@:"Inject"`
	logger    Logging             `@:"Inject"`
	container InitializingContext
	parent    Beam
	// apps      map[string]*fiber.App `@:"Inject"`
}

func (this FiberControllerConfig) New(parent Beam, container InitializingContext) *FiberControllerConfig {
	this.parent = parent
	this.container = container
	return &this
}

func (this *FiberControllerConfig) getControllerMethods() []*ControllerMethod {
	methods := []*ControllerMethod{}
	for m := range this.parent.Type().Methods() {
		pc := m.Func.Pointer()
		f := runtime.FuncForPC(pc)
		fn, _ := f.FileLine(f.Entry())

		if fn == "<autogenerated>" {
			continue
		}

		if method, found := (ControllerMethod{}).FromMethod(&m); found {
			this.logger.Debug("Detected controller method", "controller", this.parent.Type(), "method", m.Name)
			methods = append(methods, method)
		}
	}
	return methods
}

func (this *FiberControllerConfig) getInstanceHandlers(instance reflect.Value) []FiberHandler {
	handlers := []FiberHandler{}
	value := instance
	annotedType := instance.Type()
	if annotedType.Kind() == reflect.Pointer {
		value = value.Elem()
		annotedType = annotedType.Elem()
	}
	for i := range annotedType.NumField() {
		field := annotedType.Field(i)
		if field.Anonymous && field.Type.Kind() == reflect.Struct {
			if middleware, ok := value.Field(i).Addr().Interface().(FiberHandler); ok {
				this.logger.Debug("Added Handler", "name", field.Name)
				handlers = append(handlers, middleware)
			}
		}
	}
	return handlers
}

func (this *FiberControllerConfig) getInstanceFilters(instance reflect.Value) []FiberFilterHandler {
	filters := []FiberFilterHandler{}
	value := instance
	annotedType := instance.Type()
	if annotedType.Kind() == reflect.Pointer {
		value = value.Elem()
		annotedType = annotedType.Elem()
	}
	for i := range annotedType.NumField() {
		field := annotedType.Field(i)
		if field.Anonymous && field.Type.Kind() == reflect.Struct {
			if filter, ok := value.Field(i).Addr().Interface().(FiberFilterHandler); ok {
				this.logger.Debug("Added Filter", "name", field.Name)
				filters = append(filters, filter)
			}
		}
	}
	return filters
}

func (this *FiberControllerConfig) PostConstruct() Error {
	this.logger.Debug("Processing controller", "type", this.parent.Type())
	instance := this.container.GetInstance(this.parent)
	app := this.provider.Default()
	if field := FindFieldForInterface[Server](this.parent.Type()); field != nil {
		if server := GetFieldFirstTag(field, []string{"_", "Name", "Server"}); server != "" {
			a := this.provider.Provide(server)
			if a == nil {
				return NewError("InvalidServerName", fmt.Sprintf("Server configuration name %s not defined", server))
			}
			app = a
		}
	}

	methods := this.getControllerMethods()
	handlers := this.getInstanceHandlers(reflect.ValueOf(instance))
	controllerHandlers := map[reflect.Type]fiber.Handler{}

	for _, middleware := range handlers {
		if handler := middleware.Handler(); handler != nil {
			controllerHandlers[reflect.TypeOf(middleware).Elem()] = handler
		}
	}

	// filter out those defined also on methods
	filteredHandlers := slices.Clone(handlers)
	filteredHandlers = slices.DeleteFunc(filteredHandlers, func(middleware FiberHandler) bool {
		for _, method := range methods {
			if _, aValue := this.container.GetMethodAnnotedType(method.Method()); aValue.IsValid() {
				if slices.ContainsFunc(this.getInstanceHandlers(aValue), func(h FiberHandler) bool {
					return reflect.TypeOf(middleware).Elem() == reflect.TypeOf(h).Elem()
				}) {
					return true
				}
			}
		}
		return false
	})

	var router fiber.Router = app
	var routerPath string

	// A Controller without a RequestMapping Path can still be used but :
	// - each Controller methods *must* declare a RequestMapping Path.
	//
	if field := FindFieldWithAnnotation[RequestMapping](this.parent.Type()); field == nil {
		this.logger.Info("Created controller without path", "controller", this.parent.Type())
	} else if path, ok := field.Tag.Lookup("Path"); !ok || path == "" {
		this.logger.Info("Created controller without path", "controller", this.parent.Type())
	} else {
		this.logger.Info("Created controller with path", "controller", this.parent.Type(), "path", path)
		routerPath = path
		// TODO: Evaluate removing this as we have FiberPathFilter now.
		if len(methods) == 0 {
			args := []any{path}
			for _, middleware := range handlers {
				if handler, ok := controllerHandlers[reflect.TypeOf(middleware).Elem()]; ok {
					args = append(args, handler)
				}
			}
			if len(args) > 1 {
				router.Use(args...)
			}
			return nil
		}
		router = app.Group(path)
	}

	for _, method := range methods {
		defaultIn := []reflect.Value{}
		annotedType := reflect.TypeOf((*struct{})(nil)).Elem()
		routeHandlers := []fiber.Handler{}
		routeFilters := []FiberFilterHandler{}
		mt := method.Method()

		if aType, aValue := this.container.GetMethodAnnotedType(mt); aValue.IsValid() {
			this.logger.Trace("Anonymous field", "type", aValue.Type())
			annotedType = aType
			//nolint:errcheck // Not testable
			this.container.InjectMethodAnnotedValue(aValue, instance)

			for _, middleware := range handlers {
				if handler, ok := controllerHandlers[reflect.TypeOf(middleware).Elem()]; ok {
					if slices.ContainsFunc(filteredHandlers, func(h FiberHandler) bool {
						return reflect.TypeOf(middleware).Elem() == reflect.TypeOf(h).Elem()
					}) || slices.ContainsFunc(this.getInstanceHandlers(aValue), func(h FiberHandler) bool {
						return reflect.TypeOf(middleware).Elem() == reflect.TypeOf(h).Elem()
					}) {
						routeHandlers = append(routeHandlers, handler)
					}
				}
			}
			for _, middleware := range this.getInstanceHandlers(aValue) {
				if !slices.ContainsFunc(handlers, func(h FiberHandler) bool {
					return reflect.TypeOf(middleware).Elem() == reflect.TypeOf(h).Elem()
				}) {
					routeHandlers = append(routeHandlers, middleware.Handler())
				}
			}

			routeFilters = append(routeFilters, this.getInstanceFilters(aValue)...)
			defaultIn = append(defaultIn, aValue)
		} else {
			for _, middleware := range filteredHandlers {
				if handler, ok := controllerHandlers[reflect.TypeOf(middleware).Elem()]; ok {
					routeHandlers = append(routeHandlers, handler)
				}
			}
		}

		routePath := ""
		routeMethod := RequestMappingMethod{}.New().GET // "GET"
		logger := this.logger.With("controller", this.parent.Type(), "method", mt.Name, "type", mt.Type)
		if field := FindFieldWithAnnotation[RequestMapping](annotedType); field != nil {
			if path, ok := field.Tag.Lookup("Path"); ok && path != "" {
				routePath = path
			} else if routerPath == "" {
				logger.Error("No RequestMapping Path, neither on the Controller or Method")
				continue
			}
			if method, ok := field.Tag.Lookup("Method"); ok && method != "" {
				if err := routeMethod.From(method); err != nil {
					this.logger.Error("IllegalArgumentException", fmt.Sprintf("Method %s is invalid", method))
					continue
				}
			}
		} else if routerPath == "" {
			logger.Error("No RequestMapping Path, neither on the Controller or Method")
			continue
		} else {
			logger.Trace("RequestMapping not found")
		}

		handler := method.Handler(defaultIn, instance)

		filters := this.getInstanceFilters(reflect.ValueOf(instance))
		if len(routeFilters) > 0 {
			filters = append(filters, routeFilters...)
		}
		slices.Reverse(filters)
		for _, filter := range filters {
			if h, ok := handler.(fiber.Handler); ok {
				handler = any(filter.Filter(h))
			}
		}

		finalHandlers := toAny(routeHandlers)
		finalHandlers = append(finalHandlers, handler)

		switch routeMethod {
		case RequestMappingMethod{}.New().ALL:
			router.All(routePath, finalHandlers[0], finalHandlers[1:]...)
		default:
			router.Add([]string{routeMethod.String()}, routePath, finalHandlers[0], finalHandlers[1:]...)
		}

		this.logger.Info("Created controller method", "name", mt.Name, "http_method", routeMethod, "http_path", routePath)
	}

	return nil
}
